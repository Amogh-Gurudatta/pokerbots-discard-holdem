"""Offline: equity of every suit-isomorphic 3-card class vs a random 3-card hand.

Both players keep the pair chosen by the flop keep heuristic (best_keep), then showdown.
Writes src/preflop_table.py with PREFLOP_EQ = {key: equity}.
Usage: python3 tools/build_preflop.py [trials_per_class]   (~40 s with 4000 on 16 cores)
"""
import os, sys, random, itertools
from multiprocessing import Pool

from paths import SRC
sys.path.insert(0, SRC)

import strategy as S  # noqa: E402

S.init_eval_scale()


def classes():
    reps = {}
    for combo in itertools.combinations(S.ALL_CARDS, 3):
        k = S.preflop_key(combo)
        if k not in reps:
            reps[k] = combo
    return reps


def work(args):
    key, combo, n, seed = args
    rng = random.Random(seed)
    hero = [S.CI[c] for c in combo]
    deck = [c for c in S.ALL_INTS if c not in hero]
    w = 0.0
    for _ in range(n):
        s = rng.sample(deck, 8)
        opp, board = s[:3], s[3:]
        hk, _ = S.best_keep(hero, board[:3])
        ok, _ = S.best_keep(opp, board[:3])
        hv = S.eval7(list(hk) + board)
        ov = S.eval7(list(ok) + board)
        w += 1.0 if hv > ov else (0.5 if hv == ov else 0.0)
    return key, w / n


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 3000
    reps = classes()
    print("classes:", len(reps), file=sys.stderr)
    jobs = [(k, c, n, i) for i, (k, c) in enumerate(sorted(reps.items()))]
    with Pool(max(1, os.cpu_count() - 1)) as p:
        res = dict(p.map(work, jobs, chunksize=8))
    out = os.path.join(SRC, "preflop_table.py")
    with open(out, "w") as f:
        f.write("# Generated by tools/build_preflop.py (%d trials/class)\n" % n)
        f.write("PREFLOP_EQ = {\n")
        for k in sorted(res):
            f.write("%r: %.4f,\n" % (k, res[k]))
        f.write("}\n")
    top = sorted(res.items(), key=lambda kv: -kv[1])
    print("best:", top[:5], "worst:", top[-5:], file=sys.stderr)


if __name__ == "__main__":
    main()
